-- 1관문 대응표 — 지도의 분야 ↔ 국회 소관위원회
--
-- **db/rules/ 가 아니라 여기 둔다.** db/rules/*.sql 은 '선을 만드는 규칙' 이고
-- rule 표에 등록돼 있어야 한다(검사 B). 이건 규칙이 아니라 규칙이 읽는 **표**다.
-- party_side · president_term 과 같은 갈래다.
--
-- **이건 우리의 편집 판단이다.** 그래서 코드에 박지 않고 표로 두고 src 를 적는다.
-- party_side 와 같은 방식이다.
--
-- 소관위 이름은 **창고의 실측값 그대로** 쓴다 (본회의 처리 COMMITTEE_NM · 108종).
-- 지어내지 않는다 — 표에 없는 이름을 쓰면 조용히 0건이 된다.
--
-- 위원회 이름은 대수마다 바뀐다. 같은 일을 하는 옛 이름을 전부 넣는다:
--   내무 → 행정자치 → 안전행정 → 행정안전
--   재무 → 재정경제 → 기획재정
--   상공 → 상공자원 → 통상산업 → 산업자원 → 지식경제 → 산업통상자원 → 산업통상자원중소벤처기업
--   건설 → 건설교통 → 국토해양 → 국토교통
--   보건사회 → 보건복지 → 보건복지가족 → 보건복지
--
-- 'hist'(1945~1980 근현대사)는 넣지 않는다. 그 시기는 API 가 법안을 안 준다
-- (제1~9대 0건). 자동 연결 대상이 아니라는 것을 표의 부재로 말한다.

