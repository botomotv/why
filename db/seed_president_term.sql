-- 대통령 재임표 — **규칙 3이 읽는 유일한 표다.**
--
-- 규칙 3: "재임 중" ≠ "밀어붙임". 대통령 관계는 **공포일 × 이 표**로만 만든다.
-- 발의자·소관부처에서 대통령을 끌어오는 경로는 두지 않는다.
-- rule.reads 가 term_by_promulgation 에 'bill, president_term' 만 허용하는 이유다.
--
-- **날짜는 공개 기록에서 옮겨 적은 것이다. 한 번 검토가 필요하다.**
-- 임기 개시일은 헌법 제68조·70조와 공직선거법에 따른 것이고,
-- 파면은 헌법재판소 결정 선고일이다.
--
-- 권한대행 기간은 **대통령이 아니다.** 그 기간에 공포된 법은
-- "대통령 권한대행 체제" 로 표시하고 사람 이름을 주어로 쓰지 않는다.
-- 넣지 않은 것이 아니라 다른 것이므로, 아래 표에 따로 담는다.

-- 키가 (president, from_dt) 로 바뀌었다. 옛 표가 남아 있으면 다시 만든다.
DROP TABLE IF EXISTS president_term;
CREATE TABLE president_term (
  president TEXT NOT NULL,
  from_dt   TEXT NOT NULL,
  to_dt     TEXT NOT NULL,
  src       TEXT NOT NULL,
  PRIMARY KEY (president, from_dt)
);

